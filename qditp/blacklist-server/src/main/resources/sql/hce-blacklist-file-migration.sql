-- HCE 黑名单文件版本号状态表：单行表，承载 PRM.0013.9700.<版本> 的版本号分配。
-- 版本号只进不退：某一轮生成/上传失败，版本也已消耗，下一轮用新版本生成新文件，
-- ACC 侧按版本号识别新旧，NEVER 复用旧版本覆盖同名文件。
CREATE TABLE HCE_BLACKLIST_FILE_STATE (
    PARAM_TYPE      VARCHAR2(4)  NOT NULL,
    CURRENT_VERSION NUMBER(9)    NOT NULL,
    UPDATE_TIME     TIMESTAMP    NOT NULL,
    CONSTRAINT PK_HCE_BLACKLIST_FILE_STATE PRIMARY KEY (PARAM_TYPE)
);

COMMENT ON TABLE HCE_BLACKLIST_FILE_STATE IS 'HCE黑名单文件版本号状态表（单行，PARAM_TYPE=0013）';
COMMENT ON COLUMN HCE_BLACKLIST_FILE_STATE.PARAM_TYPE IS '参数类型，主键';
COMMENT ON COLUMN HCE_BLACKLIST_FILE_STATE.CURRENT_VERSION IS '当前已分配的最新文件版本号';
COMMENT ON COLUMN HCE_BLACKLIST_FILE_STATE.UPDATE_TIME IS '最近一次分配时间';

-- 首行由服务在首次分配时自动 insert（版本从 1 开始），无需预置数据。
