CREATE TABLE BLACKLIST (
    ID NUMBER(22) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CARD_ID VARCHAR2(32 CHAR) NOT NULL,
    THIRD_USER_ID VARCHAR2(16 CHAR),
    CARD_TYPE VARCHAR2(8 CHAR),
    CHANNEL_CODE VARCHAR2(2 CHAR) DEFAULT '99' NOT NULL,
    BLACK_SOURCE VARCHAR2(2 CHAR) DEFAULT '09' NOT NULL,
    BLACK_CAUSE VARCHAR2(2 CHAR) DEFAULT '09' NOT NULL,
    BIZ_NO VARCHAR2(128 CHAR),
    REASON VARCHAR2(1000 CHAR),
    CREATE_BY VARCHAR2(32 CHAR),
    CREATE_TIME TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CHANNEL_SYNC_STATUS VARCHAR2(16 CHAR),
    CHANNEL_SYNC_TIME TIMESTAMP(6),
    CHANNEL_SYNC_RETRY NUMBER(4) DEFAULT 0,
    CHANNEL_SYNC_FAIL_REASON VARCHAR2(500 CHAR),
    CONSTRAINT pk_blacklist PRIMARY KEY (ID),
    CONSTRAINT uk_blacklist_card_id UNIQUE (CARD_ID)
);

COMMENT ON TABLE BLACKLIST IS '黑名单表，只存当前生效记录，解除后整行搬至 BLACKLIST_RELEASED';
COMMENT ON COLUMN BLACKLIST.id IS '主键ID';
COMMENT ON COLUMN BLACKLIST.card_id IS '卡ID，唯一业务键；查询与解除均以本列为准';
COMMENT ON COLUMN BLACKLIST.third_user_id IS '三方用户ID，审计冗余，不参与命中判定';
COMMENT ON COLUMN BLACKLIST.card_type IS '卡类型编码（票种，如0441），出向通知契约需要';
COMMENT ON COLUMN BLACKLIST.channel_code IS '业务渠道：01地铁APP，02支付宝，99未知；黑名单域自有编码，与账户域ISSUE_ORG_CODE无对应关系';
COMMENT ON COLUMN BLACKLIST.black_source IS '发起方：01系统自动，02渠道通知，09运维手工';
COMMENT ON COLUMN BLACKLIST.black_cause IS '拉黑原因：01未付费欠费，02挂失补卡，09其他';
COMMENT ON COLUMN BLACKLIST.biz_no IS '关联业务单号，语义由channel_code与black_source共同决定，可空';
COMMENT ON COLUMN BLACKLIST.reason IS '拉黑备注，自由文本，非判定依据';
COMMENT ON COLUMN BLACKLIST.create_by IS '操作者：运维手工记管理员账号，系统触发记服务名';
COMMENT ON COLUMN BLACKLIST.create_time IS '创建时间';
COMMENT ON COLUMN BLACKLIST.channel_sync_status IS '渠道同步状态：PENDING/SUCCESS/FAILED/REJECTED';
COMMENT ON COLUMN BLACKLIST.channel_sync_time IS '渠道同步时间';
COMMENT ON COLUMN BLACKLIST.channel_sync_retry IS '渠道同步重试次数';
COMMENT ON COLUMN BLACKLIST.channel_sync_fail_reason IS '渠道同步失败原因';

CREATE INDEX idx_blacklist_third_user_id ON BLACKLIST (third_user_id);
CREATE INDEX idx_blacklist_biz_no ON BLACKLIST (biz_no);
CREATE INDEX idx_blacklist_sync_scan ON BLACKLIST (channel_sync_status, channel_sync_time);

CREATE TABLE BLACKLIST_RELEASED (
    ID NUMBER(22) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ORIGIN_ID NUMBER(22) NOT NULL,
    CARD_ID VARCHAR2(32 CHAR) NOT NULL,
    THIRD_USER_ID VARCHAR2(16 CHAR),
    CARD_TYPE VARCHAR2(8 CHAR),
    CHANNEL_CODE VARCHAR2(2 CHAR),
    BLACK_SOURCE VARCHAR2(2 CHAR),
    BLACK_CAUSE VARCHAR2(2 CHAR),
    BIZ_NO VARCHAR2(128 CHAR),
    REASON VARCHAR2(1000 CHAR),
    CREATE_BY VARCHAR2(32 CHAR),
    CREATE_TIME TIMESTAMP(6) NOT NULL,
    RELEASE_TIME TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    RELEASE_REASON VARCHAR2(500 CHAR),
    RELEASE_BY VARCHAR2(32 CHAR),
    CONSTRAINT pk_blacklist_released PRIMARY KEY (ID)
);

COMMENT ON TABLE BLACKLIST_RELEASED IS '黑名单解除历史表，保存被解除记录的完整快照；同一张卡可有多行';
COMMENT ON COLUMN BLACKLIST_RELEASED.id IS '主键ID';
COMMENT ON COLUMN BLACKLIST_RELEASED.origin_id IS '解除前在BLACKLIST中的主键ID';
COMMENT ON COLUMN BLACKLIST_RELEASED.card_id IS '卡ID，仅普通索引，NEVER建唯一约束（同卡可反复拉黑解除）';
COMMENT ON COLUMN BLACKLIST_RELEASED.third_user_id IS '三方用户ID';
COMMENT ON COLUMN BLACKLIST_RELEASED.card_type IS '卡类型编码';
COMMENT ON COLUMN BLACKLIST_RELEASED.channel_code IS '业务渠道，取值同BLACKLIST.CHANNEL_CODE';
COMMENT ON COLUMN BLACKLIST_RELEASED.black_source IS '发起方，取值同BLACKLIST.BLACK_SOURCE';
COMMENT ON COLUMN BLACKLIST_RELEASED.black_cause IS '拉黑原因，取值同BLACKLIST.BLACK_CAUSE';
COMMENT ON COLUMN BLACKLIST_RELEASED.biz_no IS '关联业务单号';
COMMENT ON COLUMN BLACKLIST_RELEASED.reason IS '原拉黑备注';
COMMENT ON COLUMN BLACKLIST_RELEASED.create_by IS '原拉黑操作者';
COMMENT ON COLUMN BLACKLIST_RELEASED.create_time IS '原拉黑时间';
COMMENT ON COLUMN BLACKLIST_RELEASED.release_time IS '解除时间';
COMMENT ON COLUMN BLACKLIST_RELEASED.release_reason IS '解除原因，NEVER复制原拉黑原因';
COMMENT ON COLUMN BLACKLIST_RELEASED.release_by IS '解除操作者';

CREATE INDEX idx_bl_released_card_id ON BLACKLIST_RELEASED (card_id);
CREATE INDEX idx_bl_released_time ON BLACKLIST_RELEASED (release_time);
CREATE INDEX idx_bl_released_biz_no ON BLACKLIST_RELEASED (biz_no);

CREATE TABLE BLACKLIST_OPERATE_LOG (
    ID NUMBER(22) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CARD_ID VARCHAR2(32 CHAR) NOT NULL,
    THIRD_USER_ID VARCHAR2(16 CHAR),
    OPERATE_TYPE VARCHAR2(32 CHAR) NOT NULL,
    OPERATOR VARCHAR2(32 CHAR),
    REASON VARCHAR2(1000 CHAR),
    OPERATE_TIME TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_blacklist_operate_log PRIMARY KEY (ID)
);

COMMENT ON TABLE BLACKLIST_OPERATE_LOG IS '黑名单操作记录表，记操作流水；完整快照见BLACKLIST_RELEASED';
COMMENT ON COLUMN BLACKLIST_OPERATE_LOG.id IS '主键ID';
COMMENT ON COLUMN BLACKLIST_OPERATE_LOG.card_id IS '卡ID';
COMMENT ON COLUMN BLACKLIST_OPERATE_LOG.third_user_id IS '三方用户ID';
COMMENT ON COLUMN BLACKLIST_OPERATE_LOG.operate_type IS '操作类型，ADD新增，DELETE删除';
COMMENT ON COLUMN BLACKLIST_OPERATE_LOG.operator IS '操作者：运维手工记管理员账号，系统触发记服务名';
COMMENT ON COLUMN BLACKLIST_OPERATE_LOG.reason IS '本次操作原因：ADD记拉黑原因，DELETE记解除原因';
COMMENT ON COLUMN BLACKLIST_OPERATE_LOG.operate_time IS '操作时间';

CREATE INDEX idx_blacklist_log_card_id ON BLACKLIST_OPERATE_LOG (card_id);
CREATE INDEX idx_blacklist_log_operate_time ON BLACKLIST_OPERATE_LOG (operate_time);
