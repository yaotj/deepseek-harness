CREATE INDEX IDX_APTD_STATUS
ON ALIPAY_PAY_TXN_DETAIL (PAY_STATUS, TXN_DATE, NEXT_REQUEST_TIME) LOCAL;

-- 欠费盘点 countUnsettledByCardId 的支撑索引。旧表这条查询是全表扫。
CREATE INDEX IDX_APTD_CARD_STATUS
