CREATE INDEX IDX_APTD_USER_DATE
ON ALIPAY_PAY_TXN_DETAIL (THIRD_USER_ID, TXN_DATE) LOCAL;

CREATE INDEX IDX_APTD_CHANNEL_ORDER
ON ALIPAY_PAY_TXN_DETAIL (CHANNEL_ORDER_NO, TXN_DATE) LOCAL;

-- 进出站关联查询（payLog/entryId、payLog/exitId、findTravelDetail）。
