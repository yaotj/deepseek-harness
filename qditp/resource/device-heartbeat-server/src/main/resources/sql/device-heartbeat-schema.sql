-- =====================================================
-- 1. 序列：心跳历史日志表ID生成器
-- =====================================================
CREATE SEQUENCE QDITP_PLAT.DEVICE_HEARTBEAT_LOG_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

-- =====================================================
-- 2. 表：DEVICE_HEARTBEAT_LOG（心跳历史日志）
--    保留每次心跳的完整记录，用于统计分析
-- =====================================================
CREATE TABLE QDITP_PLAT.DEVICE_HEARTBEAT_LOG (
    ID NUMBER(19,0) NOT NULL,
    CHANNEL VARCHAR2(2 CHAR) NOT NULL,
    DEVICE_ID VARCHAR2(32 CHAR) NOT NULL,
    STATION_CODE VARCHAR2(16 CHAR),
    HEARTBEAT_TMS TIMESTAMP(6) NOT NULL,
    REQ_BIZ_DATA CLOB,
    CREATE_TMS TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_DEVICE_HEARTBEAT_LOG PRIMARY KEY (ID)
) ORGANIZATION INDEX;

COMMENT ON TABLE QDITP_PLAT.DEVICE_HEARTBEAT_LOG IS '设备心跳历史日志表，每次心跳一条记录';
COMMENT ON COLUMN QDITP_PLAT.DEVICE_HEARTBEAT_LOG.CHANNEL IS '渠道编码：01-APP, 02-TVM, 03-BOM, 04-AGM';
COMMENT ON COLUMN QDITP_PLAT.DEVICE_HEARTBEAT_LOG.DEVICE_ID IS '设备ID，格式：站码前4位+站内序号';
COMMENT ON COLUMN QDITP_PLAT.DEVICE_HEARTBEAT_LOG.STATION_CODE IS '所属车站编码（设备号前4位）';
COMMENT ON COLUMN QDITP_PLAT.DEVICE_HEARTBEAT_LOG.HEARTBEAT_TMS IS '心跳时间';
COMMENT ON COLUMN QDITP_PLAT.DEVICE_HEARTBEAT_LOG.REQ_BIZ_DATA IS '请求中的bizData快照（可选）';

CREATE INDEX QDITP_PLAT.IDX_DHL_CHANNEL_DEVICE ON QDITP_PLAT.DEVICE_HEARTBEAT_LOG (CHANNEL, DEVICE_ID);
CREATE INDEX QDITP_PLAT.IDX_DHL_HB_TMS ON QDITP_PLAT.DEVICE_HEARTBEAT_LOG (HEARTBEAT_TMS);

-- =====================================================
-- 3. 表：DEVICE_HEARTBEAT_STATUS（设备最新心跳状态）
--    一设备一行，用于在线监控
-- =====================================================
CREATE TABLE QDITP_PLAT.DEVICE_HEARTBEAT_STATUS (
    CHANNEL VARCHAR2(2 CHAR) NOT NULL,
    DEVICE_ID VARCHAR2(32 CHAR) NOT NULL,
    STATION_CODE VARCHAR2(16 CHAR),
    LAST_HEARTBEAT_TMS TIMESTAMP(6) NOT NULL,
    HEARTBEAT_COUNT NUMBER(12) DEFAULT 1 NOT NULL,
    ONLINE_FLAG VARCHAR2(1 CHAR) DEFAULT '1' NOT NULL,
    CREATE_TMS TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATE_TMS TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_DHS PRIMARY KEY (CHANNEL, DEVICE_ID),
    CONSTRAINT CK_DHS_ONLINE CHECK (ONLINE_FLAG IN ('0', '1'))
);

COMMENT ON TABLE QDITP_PLAT.DEVICE_HEARTBEAT_STATUS IS '设备最新心跳状态，一设备一行，用MERGE INTO更新';
COMMENT ON COLUMN QDITP_PLAT.DEVICE_HEARTBEAT_STATUS.ONLINE_FLAG IS '1在线，0离线；由扫表按LAST_HEARTBEAT_TMS超时判定';

CREATE INDEX QDITP_PLAT.IDX_DHS_HB_TMS ON QDITP_PLAT.DEVICE_HEARTBEAT_STATUS (LAST_HEARTBEAT_TMS);

-- =====================================================
-- 4. 视图：设备在线状态汇总（供综管台查询）
-- =====================================================
CREATE OR REPLACE VIEW QDITP_PLAT.VW_DEVICE_HEARTBEAT_SUMMARY AS
SELECT
    CHANNEL,
    COUNT(1) AS total,
    NVL(SUM(CASE WHEN ONLINE_FLAG = '1' THEN 1 ELSE 0 END), 0) AS onlineCount,
    NVL(SUM(CASE WHEN ONLINE_FLAG = '0' THEN 1 ELSE 0 END), 0) AS offlineCount,
    TO_CHAR(MAX(LAST_HEARTBEAT_TMS), 'YYYY-MM-DD HH24:MI:SS') AS lastHeartbeatTms
FROM QDITP_PLAT.DEVICE_HEARTBEAT_STATUS
GROUP BY CHANNEL;

COMMENT ON TABLE QDITP_PLAT.VW_DEVICE_HEARTBEAT_SUMMARY IS '设备心跳状态汇总视图';
