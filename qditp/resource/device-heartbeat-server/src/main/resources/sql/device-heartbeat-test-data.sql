-- 设备心跳服务 DDL - 精简版（用于测试环境快速验证）
-- 直接在 SQL*Plus 中执行

-- 创建序列
CREATE SEQUENCE DEVICE_HEARTBEAT_LOG_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

-- 创建历史日志表
CREATE TABLE DEVICE_HEARTBEAT_LOG (
    ID NUMBER(19,0) NOT NULL PRIMARY KEY,
    CHANNEL VARCHAR2(2 CHAR) NOT NULL,
    DEVICE_ID VARCHAR2(32 CHAR) NOT NULL,
    STATION_CODE VARCHAR2(16 CHAR),
    HEARTBEAT_TMS TIMESTAMP(6) NOT NULL,
    REQ_BIZ_DATA CLOB,
    CREATE_TMS TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IDX_DHL_CHANNEL_DEVICE ON DEVICE_HEARTBEAT_LOG (CHANNEL, DEVICE_ID);
CREATE INDEX IDX_DHL_HB_TMS ON DEVICE_HEARTBEAT_LOG (HEARTBEAT_TMS);

-- 创建最新状态表
CREATE TABLE DEVICE_HEARTBEAT_STATUS (
    CHANNEL VARCHAR2(2 CHAR) NOT NULL,
    DEVICE_ID VARCHAR2(32 CHAR) NOT NULL,
    STATION_CODE VARCHAR2(16 CHAR),
    LAST_HEARTBEAT_TMS TIMESTAMP(6) NOT NULL,
    HEARTBEAT_COUNT NUMBER(12) DEFAULT 1 NOT NULL,
    ONLINE_FLAG VARCHAR2(1 CHAR) DEFAULT '1' NOT NULL,
    CREATE_TMS TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATE_TMS TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    PRIMARY KEY (CHANNEL, DEVICE_ID)
);

CREATE INDEX IDX_DHS_HB_TMS ON DEVICE_HEARTBEAT_STATUS (LAST_HEARTBEAT_TMS);

-- 插入测试数据
INSERT INTO DEVICE_HEARTBEAT_LOG (ID, CHANNEL, DEVICE_ID, STATION_CODE, HEARTBEAT_TMS, CREATE_TMS)
VALUES (DEVICE_HEARTBEAT_LOG_SEQ.NEXTVAL, '02', '06220801', '0622', SYSTIMESTAMP, SYSTIMESTAMP);

INSERT INTO DEVICE_HEARTBEAT_LOG (ID, CHANNEL, DEVICE_ID, STATION_CODE, HEARTBEAT_TMS, CREATE_TMS)
VALUES (DEVICE_HEARTBEAT_LOG_SEQ.NEXTVAL, '03', '06220802', '0622', SYSTIMESTAMP, SYSTIMESTAMP);

INSERT INTO DEVICE_HEARTBEAT_LOG (ID, CHANNEL, DEVICE_ID, STATION_CODE, HEARTBEAT_TMS, CREATE_TMS)
VALUES (DEVICE_HEARTBEAT_LOG_SEQ.NEXTVAL, '04', '06220803', '0622', SYSTIMESTAMP, SYSTIMESTAMP);

MERGE INTO DEVICE_HEARTBEAT_STATUS DHS
USING (
    SELECT '02' AS CHANNEL, '06220801' AS DEVICE_ID, '0622' AS STATION_CODE, SYSTIMESTAMP AS HB_TMS FROM DUAL
    UNION ALL
    SELECT '03' AS CHANNEL, '06220802' AS DEVICE_ID, '0622' AS STATION_CODE, SYSTIMESTAMP AS HB_TMS FROM DUAL
    UNION ALL
    SELECT '04' AS CHANNEL, '06220803' AS DEVICE_ID, '0622' AS STATION_CODE, SYSTIMESTAMP AS HB_TMS FROM DUAL
) SRC
ON (DHS.CHANNEL = SRC.CHANNEL AND DHS.DEVICE_ID = SRC.DEVICE_ID)
WHEN MATCHED THEN
    UPDATE SET LAST_HEARTBEAT_TMS = SRC.HB_TMS, HEARTBEAT_COUNT = DHS.HEARTBEAT_COUNT + 1, UPDATE_TMS = SYSTIMESTAMP
WHEN NOT MATCHED THEN
    INSERT (CHANNEL, DEVICE_ID, STATION_CODE, LAST_HEARTBEAT_TMS, HEARTBEAT_COUNT, ONLINE_FLAG, CREATE_TMS, UPDATE_TMS)
    VALUES (SRC.CHANNEL, SRC.DEVICE_ID, SRC.STATION_CODE, SRC.HB_TMS, 1, '1', SYSTIMESTAMP, SYSTIMESTAMP);

COMMIT;

-- 验证数据
SELECT CHANNEL, DEVICE_ID, STATION_CODE, ONLINE_FLAG, HEARTBEAT_COUNT FROM DEVICE_HEARTBEAT_STATUS ORDER BY CHANNEL, DEVICE_ID;
