CREATE TABLE ONLINE_ORDER (
    ORDER_NO VARCHAR(64) NOT NULL COMMENT '订单号',
    ORDER_TYPE VARCHAR(32) NOT NULL COMMENT '订单类型',
    DEVICE_ID VARCHAR(32) COMMENT '设备编号',
    ENTRY_STATION_CODE VARCHAR(16) COMMENT '起点站',
    EXIT_STATION_CODE VARCHAR(16) COMMENT '终点站',
    TICKET_PRICE INT COMMENT '票价，单位分',
    TICKET_NUM INT COMMENT '票数',
    SINGLE_TICKET_TYPE VARCHAR(8) COMMENT '单程票类型',
    TRANS_TYPE VARCHAR(8) COMMENT 'BOM交易类型',
    ADMIN_TRANS_TYPE VARCHAR(8) COMMENT 'BOM行政交易类型',
    OPERATOR_ID VARCHAR(32) COMMENT '操作员编码',
    SHIFT_ID VARCHAR(32) COMMENT '班次编码',
    BOM_OPT_SEQ VARCHAR(64) COMMENT 'BOM流水号',
    CARD_ID VARCHAR(64) COMMENT '逻辑卡号',
    TICKET_LOGIC_NUM VARCHAR(64) COMMENT '票卡逻辑号',
    TICKET_PHYSICS_NUM VARCHAR(64) COMMENT '票卡物理号',
    BEFORE_AMOUNT INT COMMENT '交易前金额',
    TRANS_AMOUNT INT COMMENT '交易金额',
    AFTER_AMOUNT INT COMMENT '交易后金额',
    PAY_CHANNEL_CODE VARCHAR(16) COMMENT '支付渠道编码',
    PAYMENT_VENDOR VARCHAR(128) COMMENT '支付账户认证码',
    PAY_RESULT VARCHAR(16) COMMENT '支付结果',
    PAY_RESULT_DESC VARCHAR(256) COMMENT '支付结果描述',
    ORDER_STATUS VARCHAR(32) COMMENT '订单状态',
    ORDER_STATUS_DESC VARCHAR(256) COMMENT '订单状态描述',
    QRCODE_GEN_DATE DATETIME COMMENT '取票二维码生成时间',
    RANDOM_FACT VARCHAR(64) COMMENT '随机因子',
    ACTUAL_TAKE_TICKET_NUM INT COMMENT '实际出票数',
    TAKE_TICKET_DATE DATETIME COMMENT '出票时间',
    TOPUP_STATUS VARCHAR(8) COMMENT '充值结果',
    BUSINESS_RESULT VARCHAR(16) COMMENT '业务结果',
    BUSINESS_RESULT_DESC VARCHAR(256) COMMENT '业务结果描述',
    FAULT_OCCUR_DATE DATETIME COMMENT '故障时间',
    FAULT_SLIP_SEQ VARCHAR(64) COMMENT '故障凭条号',
    ERROR_CODE VARCHAR(32) COMMENT '错误码',
    ERROR_MESSAGE VARCHAR(256) COMMENT '错误描述',
    CREATE_TMS DATETIME NOT NULL COMMENT '创建时间',
    UPDATE_TMS DATETIME NOT NULL COMMENT '更新时间',
    PRIMARY KEY (ORDER_NO),
    KEY IDX_ONLINE_ORDER_CARD (CARD_ID),
    KEY IDX_ONLINE_ORDER_DEVICE (DEVICE_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='互联网业务订单主表';

CREATE TABLE ONLINE_ORDER_TICKET (
    ID BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
    ORDER_NO VARCHAR(64) NOT NULL COMMENT '订单号',
    TICKET_LOGIC_NUM VARCHAR(64) COMMENT '票卡逻辑号',
    TICKET_PHYSICS_NUM VARCHAR(64) COMMENT '票卡物理号',
    TRANS_DATE DATETIME COMMENT '交易时间',
    TRANS_AMOUNT INT COMMENT '交易金额',
    CREATE_TMS DATETIME NOT NULL COMMENT '创建时间',
    PRIMARY KEY (ID),
    KEY IDX_ONLINE_ORDER_TICKET_ORDER (ORDER_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='互联网业务订单票卡明细表';

