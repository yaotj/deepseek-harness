CREATE SEQUENCE LOGIC_CARD_POOL_BATCH_SEQ
    MINVALUE 100000
    MAXVALUE 999999
    ORDER
    CACHE 2000;

CREATE TABLE LOGIC_CARD_POOL_BATCH (
    BATCH_NO NUMBER(6) NOT NULL,
    REQUEST_SEQ VARCHAR2(6 CHAR) NOT NULL,
    CARD_TYPE VARCHAR2(4 CHAR) NOT NULL,
    ACC_TICKET_TYPE VARCHAR2(2 CHAR) NOT NULL,
    REQUEST_NUM NUMBER(6) NOT NULL,
    SOURCE VARCHAR2(16 CHAR) NOT NULL,
    FILE_NAME VARCHAR2(255 CHAR),
    FTP_PATH VARCHAR2(512 CHAR),
    FILE_SIZE NUMBER(19),
    FILE_SHA256 VARCHAR2(64 CHAR),
    TOTAL_COUNT NUMBER(10) DEFAULT 0 NOT NULL,
    VALID_COUNT NUMBER(10) DEFAULT 0 NOT NULL,
    DUPLICATE_COUNT NUMBER(10) DEFAULT 0 NOT NULL,
    INVALID_COUNT NUMBER(10) DEFAULT 0 NOT NULL,
    STATUS VARCHAR2(16 CHAR) NOT NULL,
    ERROR_MSG VARCHAR2(2000 CHAR),
    RETRY_COUNT NUMBER(5) DEFAULT 0 NOT NULL,
    OPERATOR VARCHAR2(64 CHAR),
    CREATE_TIME TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    FINISH_TIME TIMESTAMP(6),
    CONSTRAINT PK_LOGIC_CARD_POOL_BATCH PRIMARY KEY (BATCH_NO),
    CONSTRAINT UK_LOGIC_CARD_POOL_BATCH_SEQ UNIQUE (REQUEST_SEQ)
);

CREATE TABLE LOGIC_CARD_POOL_CARD (
    ID NUMBER(22) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CARD_NO VARCHAR2(64 CHAR) NOT NULL,
    BATCH_NO NUMBER(6) NOT NULL,
    CARD_TYPE VARCHAR2(4 CHAR) NOT NULL,
    STATUS VARCHAR2(16 CHAR) NOT NULL,
    RESERVATION_ID VARCHAR2(36 CHAR),
    BUSINESS_TYPE VARCHAR2(32 CHAR),
    BUSINESS_ID VARCHAR2(128 CHAR),
    OWNER_ID VARCHAR2(128 CHAR),
    RESERVED_TIME TIMESTAMP(6),
    EXPIRE_TIME TIMESTAMP(6),
    CONFIRM_TIME TIMESTAMP(6),
    CREATE_TIME TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATE_TIME TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_LOGIC_CARD_POOL_CARD PRIMARY KEY (ID),
    CONSTRAINT UK_LOGIC_CARD_POOL_CARD_NO UNIQUE (CARD_NO),
    CONSTRAINT UK_LOGIC_CARD_POOL_RESERVATION UNIQUE (RESERVATION_ID),
    CONSTRAINT UK_LOGIC_CARD_POOL_BUSINESS UNIQUE (BUSINESS_TYPE, BUSINESS_ID),
    CONSTRAINT FK_LOGIC_CARD_POOL_CARD_BATCH FOREIGN KEY (BATCH_NO) REFERENCES LOGIC_CARD_POOL_BATCH(BATCH_NO)
);

CREATE TABLE LOGIC_CARD_POOL_TYPE_LOCK (
    CARD_TYPE VARCHAR2(4 CHAR) NOT NULL,
    LOCK_OWNER VARCHAR2(36 CHAR),
    LOCK_TIME TIMESTAMP(6),
    CONSTRAINT PK_LOGIC_CARD_POOL_TYPE_LOCK PRIMARY KEY (CARD_TYPE)
);

