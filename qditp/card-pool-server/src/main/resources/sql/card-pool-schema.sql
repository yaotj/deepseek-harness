CREATE INDEX IDX_LOGIC_CARD_POOL_CARD_STATUS ON LOGIC_CARD_POOL_CARD (CARD_TYPE, STATUS);
CREATE INDEX IDX_LOGIC_CARD_POOL_CARD_AVAIL ON LOGIC_CARD_POOL_CARD (CARD_TYPE, STATUS, ID);
CREATE INDEX IDX_LOGIC_CARD_POOL_BATCH_STATE ON LOGIC_CARD_POOL_BATCH (CARD_TYPE, STATUS, CREATE_TIME);

COMMENT ON TABLE LOGIC_CARD_POOL_BATCH IS '逻辑卡号批次及ACC文件导入记录';
