PROMPT === 导出前行数基线（抽样关键表）===
BEGIN
  FOR t IN (
    SELECT 'BLACKLIST'             n FROM dual UNION ALL
    SELECT 'TBL_STATION_INFO'      FROM dual UNION ALL
    SELECT 'TBL_LINE_INFO'         FROM dual UNION ALL
    SELECT 'SYS_USER'              FROM dual UNION ALL
    SELECT 'SYS_JOB'               FROM dual UNION ALL
    SELECT 'SYS_ROLE_MENU'         FROM dual UNION ALL
    SELECT 'SYS_USER_ROLE'         FROM dual UNION ALL
    SELECT 'QRTZ_JOB_DETAILS'      FROM dual
  ) LOOP
    BEGIN
      DECLARE v_cnt NUMBER;
      BEGIN
        EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM ' || '&SCHEMA.' || t.n INTO v_cnt;
        DBMS_OUTPUT.PUT_LINE(t.n || ': ' || v_cnt || ' 行');
      END;
    EXCEPTION WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE(t.n || ': [无法计数] ' || SQLERRM);
    END;
  END LOOP;
END;
