#!/bin/bash
BASE="http://172.20.211.23"
PASS=0; FAIL=0; TOTAL=0
test_api() {
  local svc=$1 port=$2 path=$3
  TOTAL=$((TOTAL+1))
  result=$(curl -s -k "${BASE}:${port}${path}" -X POST -H "Content-Type: application/json" -d '{}' 2>&1)
  if echo "$result" | grep -q 'retCode\|code\|msg'; then echo "✓ $svc $path"; PASS=$((PASS+1)); else echo "- $svc $path"; FAIL=$((FAIL+1)); fi
}
