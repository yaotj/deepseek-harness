-- 1. 风险组加管理编码
ALTER TABLE QDITP.TBL_RISK_GROUP ADD (MANAGER_CODE VARCHAR2(64 CHAR));
COMMENT ON COLUMN QDITP.TBL_RISK_GROUP.MANAGER_CODE IS '管理编码，旧系统 managerId';

-- 2. 风险规则加描述列（REMARK 语义模糊，保留旧列不删以兼容，新列承载规则描述）
ALTER TABLE QDITP.TBL_RISK_RULE ADD (RULE_DESC VARCHAR2(1000 CHAR));
COMMENT ON COLUMN QDITP.TBL_RISK_RULE.RULE_DESC IS '风险规则描述，旧系统 riskRuleDesc';
CREATE INDEX QDITP.IDX_RISK_RULE_LEVEL ON QDITP.TBL_RISK_RULE (RISK_LEVEL);

-- 3. 新建组↔规则多对多中间表
CREATE TABLE QDITP.TBL_RISK_GROUP_RULE (
    GROUP_ID    NUMBER(10) NOT NULL,
    RULE_ID     VARCHAR2(16 CHAR) NOT NULL,
    CREATE_TIME DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TBL_RISK_GROUP_RULE PRIMARY KEY (GROUP_ID, RULE_ID),
    CONSTRAINT FK_RGR_GROUP FOREIGN KEY (GROUP_ID) REFERENCES QDITP.TBL_RISK_GROUP (GROUP_ID),
    CONSTRAINT FK_RGR_RULE FOREIGN KEY (RULE_ID) REFERENCES QDITP.TBL_RISK_RULE (RULE_ID)
);
CREATE INDEX QDITP.IDX_RGR_RULE_ID ON QDITP.TBL_RISK_GROUP_RULE (RULE_ID);
COMMENT ON TABLE QDITP.TBL_RISK_GROUP_RULE IS '风险组与规则多对多绑定表（旧系统组表单 checkbox 勾选语义）';
COMMENT ON COLUMN QDITP.TBL_RISK_GROUP_RULE.GROUP_ID IS '风险组主键';
COMMENT ON COLUMN QDITP.TBL_RISK_GROUP_RULE.RULE_ID IS '风险规则编号';
COMMENT ON COLUMN QDITP.TBL_RISK_GROUP_RULE.CREATE_TIME IS '绑定时间';

-- 4. 风险记录补列（快照 + 状态/处理 + 修改时间）
ALTER TABLE QDITP.TBL_RISK_CONTROL_LOG ADD (
    RULE_NAME_SNAP         VARCHAR2(100 CHAR),
    RULE_DESC_SNAP         VARCHAR2(1000 CHAR),
    RISK_LEVEL_SNAP        NUMBER(1),
    RISK_STATUS            VARCHAR2(8 CHAR),
    RISK_HANDLE_TIME       DATE,
    RISK_HANDLE_DESC       VARCHAR2(1000 CHAR),
    RISK_HANDLE_MANAGER_ID VARCHAR2(64 CHAR),
    RISK_DEVICE_ID         VARCHAR2(32 CHAR),
    UPDATE_TIME            DATE DEFAULT SYSDATE
);
COMMENT ON COLUMN QDITP.TBL_RISK_CONTROL_LOG.RULE_NAME_SNAP IS '命中时规则名称快照，旧系统 riskRuleName';
COMMENT ON COLUMN QDITP.TBL_RISK_CONTROL_LOG.RULE_DESC_SNAP IS '命中时规则描述快照，旧系统 riskRuleDesc';
COMMENT ON COLUMN QDITP.TBL_RISK_CONTROL_LOG.RISK_LEVEL_SNAP IS '命中时风险等级快照，旧系统 riskLevel';
COMMENT ON COLUMN QDITP.TBL_RISK_CONTROL_LOG.RISK_STATUS IS '风险状态，旧系统 rsikStatus，取值语义待业主确认';
COMMENT ON COLUMN QDITP.TBL_RISK_CONTROL_LOG.RISK_HANDLE_TIME IS '风险处理时间，旧系统 riskHanleDate';
COMMENT ON COLUMN QDITP.TBL_RISK_CONTROL_LOG.RISK_HANDLE_DESC IS '风险处理描述，旧系统 riskHanleDesc';
COMMENT ON COLUMN QDITP.TBL_RISK_CONTROL_LOG.RISK_HANDLE_MANAGER_ID IS '处理人编码，旧系统 riskHanleManagerId';
COMMENT ON COLUMN QDITP.TBL_RISK_CONTROL_LOG.RISK_DEVICE_ID IS '设备ID，旧系统 riskDeviceId';
COMMENT ON COLUMN QDITP.TBL_RISK_CONTROL_LOG.UPDATE_TIME IS '最近修改时间，旧系统 updateDate';
CREATE INDEX QDITP.IDX_RISK_LOG_STATUS ON QDITP.TBL_RISK_CONTROL_LOG (RISK_STATUS);

