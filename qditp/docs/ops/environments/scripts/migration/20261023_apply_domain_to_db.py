# 覆盖 `GENERATED [ALWAYS|BY DEFAULT] [ON NULL] AS IDENTITY`
_ident_re = re.compile(r'"(\w+)"\s+\w+\([^)]*\)\s+GENERATED (ALWAYS|BY DEFAULT)(?: ON NULL)? AS IDENTITY')


# --------------------------------------------------------------------------- 解析
def split_statements(text: str):
    """按「行尾分号」累积切分；返回 (语句, 起始行号)。语句不带结尾分号。"""
    out, buf, start = [], [], 0
    for i, line in enumerate(text.splitlines(), 1):
        if not buf:
            start = i
            s = line.strip()
            if not s or s.startswith("--"):
                continue
        buf.append(line)
        if line.rstrip().endswith(";"):
            stmt = "\n".join(buf).strip()
            stmt = stmt.rstrip().rstrip(";").rstrip()   # 坑 1：OCI 不接受结尾分号
            out.append((stmt, start))
            buf = []
    return out


def parse_scheme(domain: str):
    path = SCHEME_DIR / f"QDITP_{domain}.sql"
    stmts = split_statements(path.read_text(encoding="utf-8"))
    ddl, comments, identity = [], [], []
    for sql, ln in stmts:
        joined = " ".join(sql.lstrip().split(None, 3)[0:3]).upper()
        if joined.startswith("CREATE TABLE"):
            ddl.append((sql, ln))
            m = re.match(r'CREATE TABLE "QDITP_\w+"\."(\w+)"', sql)
            table = m.group(1) if m else "?"
            for im in _ident_re.finditer(sql):
                identity.append({"table": table, "col": im.group(1), "kind": im.group(2)})
        elif joined.startswith("COMMENT ON"):
            comments.append((sql, ln))
    return ddl, comments, identity


def parse_indexes(domain: str):
    if not INDEX_FILE.exists():
        return []
    out = []
    for sql, ln in split_statements(INDEX_FILE.read_text(encoding="utf-8")):
        s = sql.lstrip()
        if re.match(r"CREATE\s+(UNIQUE\s+)?INDEX", s, re.I) and f'"QDITP_{domain}"' in s:
            out.append((sql, ln))
    return out


def parse_data(domain: str):
    """返回 [(语句, 行数, 表名)]。"""
    path = DATA_DIR / f"QDITP_{domain}.sql"
    out = []
    for sql, ln in split_statements(path.read_text(encoding="utf-8")):
        if not sql.lstrip().upper().startswith("INSERT INTO"):
            continue
        m = re.match(r'INSERT INTO "?QDITP_\w+"?\."?(\w+)"?', sql, re.I)
        table = m.group(1).upper() if m else "?"
        rows = len(re.findall(r"^[\t ]+\(", sql, re.M)) or 1
        out.append((sql, rows, table))
    return out


# --------------------------------------------------------------------------- 多行 INSERT 转换
def _split_top_level(s: str, sep: str = ","):
    """按顶层分隔符切（尊重单引号与 '' 转义、括号深度）。"""
    parts, depth, in_str, start, i = [], 0, False, 0, 0
    while i < len(s):
        ch = s[i]
        if in_str:
            if ch == "'":
                if i + 1 < len(s) and s[i + 1] == "'":
                    i += 2
                    continue
                in_str = False
        else:
            if ch == "'":
                in_str = True
            elif ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
            elif ch == sep and depth == 0:
                parts.append(s[start:i])
                start = i + 1
        i += 1
    parts.append(s[start:])
    return parts


def to_oracle_insert(sql: str, virtual_cols: set | None = None) -> str:
    """两件事：
    1. 剔除虚拟列（`GENERATED ALWAYS AS (…) VIRTUAL`）—— Oracle 不允许对它 INSERT（ORA-54013，
       实测 USER_ITP_REG_INFO.THIRD_USER_ID_SUFFIX / RIDE.QRCODE_STATUS.CARD_ID_TAIL 中招）。
    2. MySQL 风格 `INSERT ... VALUES (..),(..)` → Oracle `INSERT ALL ... SELECT 1 FROM DUAL`。
    """
    s = sql.strip()
    m = re.match(r"(?is)^INSERT\s+INTO\s+(\S+)\s*", s)
    if not m:
        return sql
    tbl = m.group(1)
    i = m.end()
    if i >= len(s) or s[i] != "(":
        return sql
    depth, in_str, j = 0, False, i
    while j < len(s):
        ch = s[j]
        if in_str:
            if ch == "'":
                if j + 1 < len(s) and s[j + 1] == "'":
                    j += 2
                    continue
                in_str = False
        else:
            if ch == "'":
                in_str = True
            elif ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
                if depth == 0:
                    break
        j += 1
    cols_txt = s[i:j + 1]
    mv = re.match(r"(?is)\s*VALUES\s*", s[j + 1:])
    if not mv:
        return sql
    rest = s[j + 1 + mv.end():]
    tuples = [t.strip() for t in _split_top_level(rest) if t.strip()]

    # ---- 剔除虚拟列
    cols = [c.strip() for c in _split_top_level(cols_txt[1:-1])]
    keep = [k for k, c in enumerate(cols) if c.strip('"').upper() not in (virtual_cols or set())]
    if len(keep) != len(cols):
        cols_txt = "(" + ", ".join(cols[k] for k in keep) + ")"
        new_tuples = []
        for t in tuples:
            if not (t.startswith("(") and t.endswith(")")):
                return sql
            parts = _split_top_level(t[1:-1])
            if len(parts) != len(cols):      # 结构不符，放弃剔除（宁可不导也不写错）
                return sql
            new_tuples.append("(" + ", ".join(parts[k] for k in keep) + ")")
        tuples = new_tuples

    if len(tuples) <= 1:
        return f"INSERT INTO {tbl} {cols_txt} VALUES {tuples[0]}" if tuples else sql
    lines = ["INSERT ALL"]
    for t in tuples:
        lines.append(f"INTO {tbl} {cols_txt} VALUES {t}")
    lines.append("SELECT 1 FROM DUAL")
    return "\n".join(lines)


# --------------------------------------------------------------------------- DB
def ora_code(exc) -> str:
    m = re.search(r"(ORA-\d{5})", str(exc))
    return m.group(1) if m else "?"


def run(cur, sql, errors, tag, lineno=None, ignore=IGNORABLE):
    try:
        cur.execute(sql)
        return True
    except Exception as exc:  # noqa: BLE001
        code = ora_code(exc)
        if code in ignore:
            return "skip"
        errors.append({"tag": tag, "line": lineno, "code": code, "msg": str(exc)[:300]})
        return False


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--domain", default="PLAT")
    ap.add_argument("--dsn", default=os.getenv("QDITP_DSN", DEFAULT_DSN))
    ap.add_argument("--user", default=None)
    ap.add_argument("--password", default=None)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--execute", action="store_true")
    ap.add_argument("--skip-scheme", action="store_true")
    ap.add_argument("--skip-index", action="store_true")
    ap.add_argument("--skip-data", action="store_true")
    ap.add_argument("--skip-seq", action="store_true")
    ap.add_argument("--no-clean", action="store_true", help="灌数前不 DELETE 存量行（默认会清）")
    ap.add_argument("--only-table", default=None, help="只处理指定表的数据（修单表用，自动跳过 DDL/索引）")
    ap.add_argument("--commit-every", type=int, default=1000)
    args = ap.parse_args()

    domain = args.domain.upper()
    user = args.user or f"QDITP_{domain}"
    pwd = args.password or os.getenv("QDITP_DOMAIN_PWD")

    if not (args.dry_run or args.execute):
        print("请指定 --dry-run 或 --execute"); return 2

    ddl, comments, identity = parse_scheme(domain)
    idx = parse_indexes(domain)
    data = parse_data(domain)
    if args.only_table:
        want = args.only_table.upper()
        data = [d for d in data if d[2].upper() == want]
        print(f"[only-table] 只处理 {want}，命中 {len(data)} 条 INSERT")
    data_tables = {t for _, _, t in data}
    expected = Counter()
    for _, rows, table in data:
        expected[table] += rows
    id_with_data = [x for x in identity if x["table"] in data_tables and x["kind"] == "ALWAYS"]

    print(f"=== 解析结果（{domain}）===")
    print(f"  CREATE TABLE : {len(ddl)}   COMMENT ON : {len(comments)}   补充索引 : {len(idx)}")
    print(f"  INSERT 语句  : {len(data)}   涉及表 : {len(expected)}   期望行数 : {sum(expected.values()):,}")
    print(f"  IDENTITY 列  : {len(identity)}（ALWAYS 且有数据: {len(id_with_data)}"
          f"{' → 建表时临时降 BY DEFAULT' if id_with_data else ''}）")

    if args.dry_run:
        conv = sum(1 for sql, _, _ in data if to_oracle_insert(sql) != sql.strip())
        bad = [s for s, _, _ in data if "VALUES" not in s.upper()]
        print(f"\n[DRY-RUN] 需转 INSERT ALL 的语句 {conv}/{len(data)}，缺 VALUES {len(bad)}")
        print("[DRY-RUN] 未连库、未做任何写操作")
        return 0

    if not pwd:
        print("缺少口令：设置 QDITP_DOMAIN_PWD 或 --password"); return 2

    import oracledb

    LOG_DIR.mkdir(parents=True, exist_ok=True)
    log_path = LOG_DIR / f"apply_{domain}_{datetime.now():%Y%m%d_%H%M%S}.log"
    logf = open(log_path, "w", encoding="utf-8")

    def log(msg: str):
        print(msg)
        logf.write(msg + "\n")
        logf.flush()

    log(f"=== 目标 {user}@{args.dsn} | 域 {domain} | {datetime.now():%Y-%m-%d %H:%M:%S} ===")
    conn = oracledb.connect(user=user, password=pwd, dsn=args.dsn)
    cur = conn.cursor()
    if args.only_table:
        args.skip_scheme = args.skip_index = True
    # 虚拟列：Oracle 不允许 INSERT（ORA-54013），导数据时 MUST 从列清单里剔掉
    cur.execute("select table_name, column_name from user_tab_cols where virtual_column='YES'")
    virtual_by_table = {}
    for tb, col in cur.fetchall():
        virtual_by_table.setdefault(tb.upper(), set()).add(col.upper())
    if virtual_by_table:
        print("  虚拟列（导数据时剔除）:", {k: sorted(v) for k, v in virtual_by_table.items()})
    errors: list[dict] = []
    t0 = time.time()

    # ---------------- 1. 建表 + 注释
    if not args.skip_scheme:
        log(f"\n[1/5] 建表 {len(ddl)} 张 ...")
        ok = skip = fail = 0
        for i, (sql, ln) in enumerate(ddl, 1):
            if id_with_data:
                m = re.match(r'CREATE TABLE "QDITP_\w+"\."(\w+)"', sql)
                if m and any(x["table"] == m.group(1) for x in id_with_data):
                    sql = sql.replace("GENERATED ALWAYS AS IDENTITY", "GENERATED BY DEFAULT AS IDENTITY")
            r = run(cur, sql, errors, "DDL", ln)
            ok += 1 if r is True else 0
            skip += 1 if r == "skip" else 0
            fail += 1 if r is False else 0
            if i % 25 == 0:
                log(f"    表 {i}/{len(ddl)}  ok={ok} skip={skip} fail={fail}")
        conn.commit()
        log(f"  建表完成: ok={ok} skip={skip} fail={fail}")

        log(f"\n[2/5] 注释 {len(comments)} 条 ...")
        ok = fail = 0
        for sql, ln in comments:
            r = run(cur, sql, errors, "COMMENT", ln)
            ok += 1 if r is True else 0
            fail += 1 if r is False else 0
        conn.commit()
        log(f"  注释完成: ok={ok} fail={fail}")

    # ---------------- 2. 补充索引
    if not args.skip_index and idx:
        log(f"\n[3/5] 补充索引 {len(idx)} 个 ...")
        ok = skip = fail = 0
        for sql, ln in idx:
            r = run(cur, sql, errors, "INDEX", ln)
            ok += 1 if r is True else 0
            skip += 1 if r == "skip" else 0
            fail += 1 if r is False else 0
        conn.commit()
        log(f"  索引完成: ok={ok} skip={skip} fail={fail}")

    # ---------------- 3. 清残留 + 灌数
    if not args.skip_data:
        order = []
        for _, _, t in data:
            if t not in order:
                order.append(t)
        if not args.no_clean:
            log(f"\n[3.5] 清理 {len(order)} 张目标表存量行（倒序=子表先删）...")
            cleared = 0
            for t in reversed(order):
                try:
                    cur.execute(f'DELETE FROM "{t}"')
                    cleared += cur.rowcount or 0
                except Exception as exc:  # noqa: BLE001
                    errors.append({"tag": f"CLEAN:{t}", "code": ora_code(exc), "msg": str(exc)[:200]})
            conn.commit()
            log(f"  清理完成，删除 {cleared} 行")

        log(f"\n[4/5] 灌数 {len(data)} 条语句（{sum(expected.values()):,} 行，多行 VALUES → INSERT ALL）...")
        done = rows_done = fail = 0
        for i, (sql, rows, table) in enumerate(data, 1):
            try:
                cur.execute(to_oracle_insert(sql, virtual_by_table.get(table.upper())))
                rows_done += rows
            except Exception as exc:  # noqa: BLE001
                fail += 1
                errors.append({"tag": f"DATA:{table}", "line": i, "code": ora_code(exc), "msg": str(exc)[:300]})
            done += 1
            if done % args.commit_every == 0:
                conn.commit()
                log(f"    {done}/{len(data)} 语句 | {rows_done:,} 行 | 失败 {fail} | {time.time()-t0:.0f}s")
        conn.commit()
        log(f"  灌数完成: {done} 语句 / 约 {rows_done:,} 行 / 失败 {fail}")

    # ---------------- 4. 序列：补建缺失 + 校准
    if not args.skip_seq:
        log("\n[5/5] 序列补建与校准 ...")
        for item in SEQUENCES.get(domain, []):
            seq, ddl, table, col = item["name"], item["ddl"], item["table"], item["col"]
            try:
                cur.execute("select count(*) from user_sequences where sequence_name=:1", [seq])
                if cur.fetchone()[0] == 0:
                    cur.execute(f'CREATE SEQUENCE "{seq}" {ddl}')
                    log(f"  {seq:32s} 缺失 → 已补建（{ddl}）")
                if not table or not col:
                    log(f"  {seq:32s} 循环计数器，不校准")
                    continue
                cur.execute(f'SELECT NVL(MAX("{col}"),0) FROM "{table}"')
                mx = int(cur.fetchone()[0] or 0)
                nxt = mx + 1
                lim = item.get("maxvalue")
                if lim and nxt > lim:
                    log(f"  {seq:32s} ⚠️ MAX({col})={mx} 已顶到 MAXVALUE={lim}，跳过 RESTART（需人工裁决）")
                    continue
                cur.execute(f'ALTER SEQUENCE "{seq}" RESTART START WITH {nxt}')
                log(f"  {seq:32s} -> {nxt}（{table}.{col} max={mx}）")
            except Exception as exc:  # noqa: BLE001
                errors.append({"tag": f"SEQ:{seq}", "code": ora_code(exc), "msg": str(exc)[:200]})
                log(f"  {seq:32s} 失败: {ora_code(exc)} {str(exc).splitlines()[0][:80]}")

        for x in identity:
            stmt = (f'ALTER TABLE "{x["table"]}" MODIFY ("{x["col"]}" '
                    f'GENERATED {x["kind"]} AS IDENTITY (START WITH LIMIT VALUE))')
            try:
                cur.execute(stmt)
            except Exception as exc:  # noqa: BLE001
                errors.append({"tag": f"IDENT:{x['table']}.{x['col']}", "code": ora_code(exc), "msg": str(exc)[:200]})
        conn.commit()
        log(f"  identity 列校准 {len(identity)} 个（失败 {sum(1 for e in errors if e['tag'].startswith('IDENT'))}）")

    # ---------------- 5. 校验
    log("\n=== 校验 ===")
    cur.execute("select count(*) from user_tables")
    ntables = cur.fetchone()[0]
    cur.execute("select count(*) from user_indexes")
    nidx = cur.fetchone()[0]
    cur.execute("select count(*) from user_sequences")
    nseq = cur.fetchone()[0]
    log(f"  user_tables={ntables}  user_indexes={nidx}  user_sequences={nseq}")

    mismatch, total_db = [], 0
    for table, exp in sorted(expected.items()):
        try:
            cur.execute(f'SELECT COUNT(*) FROM "{table}"')
            got = cur.fetchone()[0]
        except Exception as exc:  # noqa: BLE001
            log(f"  [ERR] {table:34s} 查询失败 {ora_code(exc)}"); continue
        total_db += got
        if got != exp:
            mismatch.append((table, exp, got))
    log(f"  表行数合计: 库中 {total_db:,} vs 期望 {sum(expected.values()):,}")
    log(f"  有数据表 {len(expected)} 张，行数不一致 {len(mismatch)} 张")
    for t, e, g in mismatch[:30]:
        log(f"    [DIFF] {t:34s} 期望 {e:>8,} 实际 {g:>8,}")

    log(f"\n=== 错误汇总（{len(errors)}）===")
    cnt = Counter(e["code"] for e in errors)
    log("  按错误码: " + ", ".join(f"{k}={v}" for k, v in cnt.most_common(10)))
    for e in errors[:30]:
        log(f"  {e['code']} {e['tag']} line={e.get('line')} :: {e['msg'][:150]}")

    log(f"\n完成，用时 {time.time()-t0:.0f}s，日志 {log_path}")
    conn.close()
    logf.close()
    return 0 if not errors and not mismatch else 1


