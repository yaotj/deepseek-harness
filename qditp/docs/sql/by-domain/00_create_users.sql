SET DEFINE OFF
SET VERIFY OFF
WHENEVER SQLERROR CONTINUE

-- Step 0：现查（NEVER 跳过；旧脚本把红岛值写进 PL/SQL 断言，换环境会直接 EXIT）
-- SELECT sys_context('USERENV','CON_NAME') AS pdb,
