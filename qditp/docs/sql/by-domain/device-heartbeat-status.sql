SET DEFINE OFF
SET SQLBLANKLINES ON
WHENEVER SQLERROR CONTINUE
ALTER SESSION SET CURRENT_SCHEMA = QDITP_PLAT;

-- ==================== 建表 ====================

-- ------ 表 DEVICE_HEARTBEAT_STATUS ------
CREATE TABLE "QDITP_PLAT"."DEVICE_HEARTBEAT_STATUS" 
   (	"CHANNEL" VARCHAR2(2 CHAR) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"DEVICE_ID" VARCHAR2(32 CHAR) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"STATION_CODE" VARCHAR2(16 CHAR) COLLATE "USING_NLS_COMP", 
	"LAST_HEARTBEAT_TMS" TIMESTAMP (6) NOT NULL ENABLE, 
	"HEARTBEAT_COUNT" NUMBER (12,0) DEFAULT 1 NOT NULL ENABLE, 
	"ONLINE_FLAG" VARCHAR2(1 CHAR) COLLATE "USING_NLS_COMP" DEFAULT '1' NOT NULL ENABLE, 
	"CREATE_TMS" TIMESTAMP (6) DEFAULT SYSTIMESTAMP NOT NULL ENABLE, 
	"UPDATE_TMS" TIMESTAMP (6) DEFAULT SYSTIMESTAMP NOT NULL ENABLE, 
	 CONSTRAINT "CK_DHS_ONLINE" CHECK (ONLINE_FLAG IN ('0', '1')) ENABLE, 
	 CONSTRAINT "PK_DEVICE_HEARTBEAT_STATUS" PRIMARY KEY ("CHANNEL", "DEVICE_ID")
	  USING INDEX  ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;

COMMENT ON TABLE "QDITP_PLAT"."DEVICE_HEARTBEAT_STATUS" IS '设备最新心跳状态，一设备一行，MERGE INTO更新；channel: 01-APP,02-TVM,03-BOM,04-AGM';
COMMENT ON COLUMN "QDITP_PLAT"."DEVICE_HEARTBEAT_STATUS"."CHANNEL" IS '渠道编码：01-APP, 02-TVM, 03-BOM, 04-AGM';
COMMENT ON COLUMN "QDITP_PLAT"."DEVICE_HEARTBEAT_STATUS"."DEVICE_ID" IS '设备ID，格式：站码前4位+站内序号';
COMMENT ON COLUMN "QDITP_PLAT"."DEVICE_HEARTBEAT_STATUS"."STATION_CODE" IS '所属车站编码（设备号前4位）';
COMMENT ON COLUMN "QDITP_PLAT"."DEVICE_HEARTBEAT_STATUS"."LAST_HEARTBEAT_TMS" IS '最新心跳时间';
COMMENT ON COLUMN "QDITP_PLAT"."DEVICE_HEARTBEAT_STATUS"."HEARTBEAT_COUNT" IS '累计心跳次数';
COMMENT ON COLUMN "QDITP_PLAT"."DEVICE_HEARTBEAT_STATUS"."ONLINE_FLAG" IS '在线标志：1在线，0离线；由扫表按LAST_HEARTBEAT_TMS超时判定';

-- ==================== 索引 ====================

CREATE INDEX "QDITP_PLAT"."IDX_DHS_HB_TMS" ON "QDITP_PLAT"."DEVICE_HEARTBEAT_STATUS" ("LAST_HEARTBEAT_TMS");

-- ==================== 视图 ====================

CREATE OR REPLACE VIEW "QDITP_PLAT"."VW_DEVICE_HEARTBEAT_SUMMARY" AS
SELECT
    CHANNEL,
    COUNT(1) AS total,
    NVL(SUM(CASE WHEN ONLINE_FLAG = '1' THEN 1 ELSE 0 END), 0) AS onlineCount,
    NVL(SUM(CASE WHEN ONLINE_FLAG = '0' THEN 1 ELSE 0 END), 0) AS offlineCount,
    TO_CHAR(MAX(LAST_HEARTBEAT_TMS), 'YYYY-MM-DD HH24:MI:SS') AS lastHeartbeatTms
FROM "QDITP_PLAT"."DEVICE_HEARTBEAT_STATUS"
GROUP BY CHANNEL;

COMMENT ON TABLE "QDITP_PLAT"."VW_DEVICE_HEARTBEAT_SUMMARY" IS '设备心跳状态汇总视图';

COMMIT;
