#!/usr/bin/env python3
"""从 old-graylist-raw.json 生成两种导入 SQL（旧 ITP 灰名单 -> 新 ITP 测试环境）。
   Option A: 保真镜像表 GRAYLIST_LEGACY（1821 行，不丢字段）—— 推荐
   Option B: 按卡聚合进现有 GRAYLIST（948 行，丢失逐规则明细）—— 仅在业主确认"新观察名单"口径时用
   两个脚本都幂等，且各自附带回滚脚本。执行时间：2026-11-18 网络恢复后。
"""
import json, os
from collections import defaultdict

BASE = os.path.dirname(os.path.abspath(__file__))
rows = json.load(open(os.path.join(BASE, 'old-graylist-raw.json'), encoding='utf-8'))['list']


def esc(s):
    if s is None:
        return 'NULL'
    return "'" + str(s).replace("'", "''") + "'"


def ts(s):
    """'YYYY-MM-DD HH24:MI:SS' -> Oracle TO_TIMESTAMP；空 -> NULL"""
    if not s:
        return 'NULL'
    return f"TO_TIMESTAMP({esc(s)},'YYYY-MM-DD HH24:MI:SS')"


# ---------------- Option A: 保真镜像表 ----------------
a = []
a.append('-- ============================================================')
a.append('-- Option A（推荐·保真）旧 ITP 灰名单 -> 新系统 GRAYLIST_LEGACY')
a.append('-- 数据来源：docs/testing/admin-web/graylist-export-2026-11-17/old-graylist-raw.json')
a.append('-- 1821 行 / 948 张卡 / 4 风险规则；逐字段保真，不丢「风险规则+发生次数+最后发生时间」。')
a.append('-- 幂等：DROP 后重建（或先跑回滚脚本）；执行前 MUST 确认新库无同名表。')
a.append('-- ============================================================')
a.append('')
a.append('CREATE TABLE GRAYLIST_LEGACY (')
a.append('    ID NUMBER(22) GENERATED BY DEFAULT AS IDENTITY NOT NULL,')
a.append('    USER_ID VARCHAR2(32 CHAR) NOT NULL,')
a.append('    RISK_RULE_NAME VARCHAR2(128 CHAR) NOT NULL,')
a.append('    RISK_OCCUR_TIMES NUMBER(10),')
a.append('    RISK_OCCURS_LAST_DATE TIMESTAMP(6),')
a.append('    MANAGER_ID VARCHAR2(64 CHAR),')
a.append('    REG_DATE TIMESTAMP(6),')
a.append('    UPDATE_DATE TIMESTAMP(6),')
a.append('    MIGRATE_BATCH VARCHAR2(32 CHAR) DEFAULT \'OLD-ITP-20261118\' NOT NULL,')
a.append('    CONSTRAINT pk_graylist_legacy PRIMARY KEY (ID),')
a.append('    CONSTRAINT uk_graylist_legacy UNIQUE (USER_ID, RISK_RULE_NAME)')
a.append(');')
a.append('COMMENT ON TABLE GRAYLIST_LEGACY IS \'旧ITP灰名单保真迁移表（风控规则台账，只读口径）；源 docs/testing/admin-web/graylist-export-2026-11-17\';')
a.append('COMMENT ON COLUMN GRAYLIST_LEGACY.USER_ID IS \'逻辑卡号(旧 userId)\';')
a.append('COMMENT ON COLUMN GRAYLIST_LEGACY.RISK_RULE_NAME IS \'风险规则名称(旧 riskRuleId，非编码)\';')
a.append('COMMENT ON COLUMN GRAYLIST_LEGACY.RISK_OCCUR_TIMES IS \'风险发生次数(旧 riskRuleIdTimes)\';')
a.append('COMMENT ON COLUMN GRAYLIST_LEGACY.RISK_OCCURS_LAST_DATE IS \'风险发生最后时间(旧 riskOccursLastDate)\';')
a.append('COMMENT ON COLUMN GRAYLIST_LEGACY.MANAGER_ID IS \'管理编码(旧 managerId，超级管理员等)\';')
a.append('COMMENT ON COLUMN GRAYLIST_LEGACY.REG_DATE IS \'入库时间(旧 regDate)\';')
a.append('COMMENT ON COLUMN GRAYLIST_LEGACY.UPDATE_DATE IS \'更新时间(旧 updateDate，可空)\';')
a.append('')
a.append('CREATE INDEX idx_gl_legacy_user ON GRAYLIST_LEGACY (USER_ID);')
a.append('CREATE INDEX idx_gl_legacy_rule ON GRAYLIST_LEGACY (RISK_RULE_NAME);')
a.append('')
a.append('-- --- 1821 行数据 ---')
for r in rows:
    a.append(
        "INSERT INTO GRAYLIST_LEGACY (USER_ID,RISK_RULE_NAME,RISK_OCCUR_TIMES,RISK_OCCURS_LAST_DATE,MANAGER_ID,REG_DATE,UPDATE_DATE) "
        "VALUES ({u},{rule},{times},{last},{mgr},{reg},{upd});".format(
            u=esc(r.get('userId')),
            rule=esc(r.get('riskRuleId')),
            times=('NULL' if r.get('riskRuleIdTimes') is None else str(r.get('riskRuleIdTimes'))),
            last=ts(r.get('riskOccursLastDate')),
            mgr=esc(r.get('managerId')),
            reg=ts(r.get('regDate')),
            upd=ts(r.get('updateDate')),
        )
    )
a.append('')
a.append('COMMIT;')
a.append('-- 验证：SELECT COUNT(*) FROM GRAYLIST_LEGACY;  -- 期望 1821')
a.append('--       SELECT COUNT(DISTINCT USER_ID) FROM GRAYLIST_LEGACY;  -- 期望 948')
open(os.path.join(BASE, 'import-A-faithful-GRAYLIST_LEGACY.sql'), 'w', encoding='utf-8').write('\n'.join(a) + '\n')

# rollback A
open(os.path.join(BASE, 'rollback-A-drop-GRAYLIST_LEGACY.sql'), 'w', encoding='utf-8').write(
    '-- 回滚 Option A：删除保真镜像表（不可恢复，执行前确认已留存 raw.json/csv）\n'
    'DROP INDEX idx_gl_legacy_rule;\n'
    'DROP INDEX idx_gl_legacy_user;\n'
    'DROP TABLE GRAYLIST_LEGACY PURGE;\n'
    'COMMIT;\n'
)

# ---------------- Option B: 聚合进现有 GRAYLIST ----------------
bycard = defaultdict(list)
for r in rows:
    bycard[r['userId']].append(r)

b = []
b.append('-- ============================================================')
b.append('-- Option B（有损·按卡聚合）旧 ITP 灰名单 -> 现有 GRAYLIST')
b.append('-- ⚠ 语义不同：现有 GRAYLIST 是「运维手工观察名单」，此处塞入的是「风控规则命中累计」。')
b.append('-- ⚠ 有损：948 行（按卡去重），逐规则明细/发生次数/最后发生时间压进 REASON 文本，不可结构化查询。')
b.append('-- 仅在业主确认「新观察名单口径、旧台账明细不需要」时用；否则用 Option A。')
b.append('-- 幂等标记：CREATE_BY = \'LEGACY_MIGRATE_20261118\'；重跑前先执行本文件开头的 DELETE。')
b.append('-- ============================================================')
b.append('')
b.append("DELETE FROM GRAYLIST WHERE CREATE_BY = 'LEGACY_MIGRATE_20261118';")
b.append('')
b.append('-- --- 948 行（按卡聚合）---')
for card, recs in sorted(bycard.items()):
    parts = []
    for r in recs:
        rule = r.get('riskRuleId') or ''
        times = r.get('riskRuleIdTimes')
        last = r.get('riskOccursLastDate') or ''
        parts.append(f"{rule}×{'' if times is None else times}次(最后{last})")
    reason = '旧ITP灰名单迁移(风控规则命中): ' + '; '.join(parts)
    reg_dates = [r.get('regDate') for r in recs if r.get('regDate')]
    earliest = min(reg_dates) if reg_dates else None
    b.append(
        "INSERT INTO GRAYLIST (CARD_ID,GRAY_SOURCE,REASON,CREATE_BY,CREATE_TIME) "
        "VALUES ({card},'01',{reason},'LEGACY_MIGRATE_20261118',{ct});".format(
            card=esc(card),
            reason=esc(reason[:1000]),
            ct=ts(earliest),
        )
    )
b.append('')
b.append('COMMIT;')
b.append('-- 验证：SELECT COUNT(*) FROM GRAYLIST WHERE CREATE_BY=\'LEGACY_MIGRATE_20261118\'; -- 期望 948')
open(os.path.join(BASE, 'import-B-aggregate-into-GRAYLIST.sql'), 'w', encoding='utf-8').write('\n'.join(b) + '\n')

# rollback B
open(os.path.join(BASE, 'rollback-B-clean-LEGACY_MIGRATE.sql'), 'w', encoding='utf-8').write(
    "-- 回滚 Option B：只删本次迁移标记行，不动运维手工进灰数据\n"
    "DELETE FROM GRAYLIST WHERE CREATE_BY = 'LEGACY_MIGRATE_20261118';\n"
    "COMMIT;\n"
    "-- 验证：SELECT COUNT(*) FROM GRAYLIST WHERE CREATE_BY='LEGACY_MIGRATE_20261118'; -- 期望 0\n"
)

print('Option A rows:', len(rows))
print('Option B rows:', len(bycard))
print('generated 4 SQL files + 2 data files')
