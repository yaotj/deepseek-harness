-- 灰名单表（对标旧 ITP「灰名单管理」，新系统补齐名单域的最小形态）。
--
-- 与黑名单的边界：灰名单只是「观察/预警」名单，不参与乘车拦截与渠道同步，
-- 因此刻意 NOT 引入 BLACKLIST 的 channel_sync_* 四列与两阶段解除机制；
-- 若后续要升级成拦截语义，MUST 走黑名单同款「当前生效 + 整行搬迁流水」重构，而非在灰名单上打补丁。
--
-- 存量说明：旧 ITP 灰名单 1808 条（2026-11-03 实扫）在旧库，本表不迁移；
-- 是否迁移与旧数据运营口径以 docs/testing/新旧ITP综管台对标-2026-11-03.md §6 业主裁定为准。

CREATE TABLE GRAYLIST (
    ID NUMBER(22) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CARD_ID VARCHAR2(32 CHAR) NOT NULL,
    THIRD_USER_ID VARCHAR2(16 CHAR),
    CARD_TYPE VARCHAR2(8 CHAR),
    GRAY_SOURCE VARCHAR2(2 CHAR) DEFAULT '09' NOT NULL,
    BIZ_NO VARCHAR2(128 CHAR),
    REASON VARCHAR2(1000 CHAR),
    CREATE_BY VARCHAR2(32 CHAR),
    CREATE_TIME TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_graylist PRIMARY KEY (ID),
    CONSTRAINT uk_graylist_card_id UNIQUE (CARD_ID)
);

COMMENT ON TABLE GRAYLIST IS '灰名单表（观察/预警），只存当前在灰记录，移出后操作流水记 GRAYLIST_OPERATE_LOG';
COMMENT ON COLUMN GRAYLIST.id IS '主键ID';
COMMENT ON COLUMN GRAYLIST.card_id IS '卡ID，唯一业务键';
COMMENT ON COLUMN GRAYLIST.third_user_id IS '三方用户ID，审计冗余';
COMMENT ON COLUMN GRAYLIST.card_type IS '卡类型编码（票种，如0441）';
COMMENT ON COLUMN GRAYLIST.gray_source IS '发起方：01系统自动，09运维手工';
COMMENT ON COLUMN GRAYLIST.biz_no IS '关联业务单号，可空';
COMMENT ON COLUMN GRAYLIST.reason IS '进灰备注，自由文本';
COMMENT ON COLUMN GRAYLIST.create_by IS '操作者：运维手工记管理员账号，系统触发记服务名';
COMMENT ON COLUMN GRAYLIST.create_time IS '进灰时间';

CREATE INDEX idx_graylist_third_user_id ON GRAYLIST (third_user_id);
CREATE INDEX idx_graylist_biz_no ON GRAYLIST (biz_no);

CREATE TABLE GRAYLIST_OPERATE_LOG (
    ID NUMBER(22) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CARD_ID VARCHAR2(32 CHAR) NOT NULL,
    THIRD_USER_ID VARCHAR2(128),
    OPERATE_TYPE VARCHAR2(16) NOT NULL,
    OPERATOR VARCHAR2(32 CHAR),
    REASON VARCHAR2(1000 CHAR),
    OPERATE_TIME TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_graylist_operate_log PRIMARY KEY (ID)
);

COMMENT ON TABLE GRAYLIST_OPERATE_LOG IS '灰名单操作记录表，记进灰/移出流水';
COMMENT ON COLUMN GRAYLIST_OPERATE_LOG.id IS '主键ID';
COMMENT ON COLUMN GRAYLIST_OPERATE_LOG.card_id IS '卡ID';
COMMENT ON COLUMN GRAYLIST_OPERATE_LOG.third_user_id IS '三方用户ID';
COMMENT ON COLUMN GRAYLIST_OPERATE_LOG.operate_type IS '操作类型，ADD进灰，REMOVE移出';
COMMENT ON COLUMN GRAYLIST_OPERATE_LOG.operator IS '操作者';
COMMENT ON COLUMN GRAYLIST_OPERATE_LOG.reason IS '本次操作原因：ADD记进灰原因，REMOVE记移出原因';
COMMENT ON COLUMN GRAYLIST_OPERATE_LOG.operate_time IS '操作时间';

CREATE INDEX idx_graylist_log_card_id ON GRAYLIST_OPERATE_LOG (card_id);
CREATE INDEX idx_graylist_log_operate_time ON GRAYLIST_OPERATE_LOG (operate_time);
