-- ============================================================
-- 99 · 变更后还原（2026-11-06 综管台对标补建 + UI 优化落库）
-- ============================================================
-- 用途：把 00-backup-before.sql 落下的快照还原回业务表。
-- 执行环境：测试库 AFCITPDB
-- ⚠️ 顺序 MUST 与变更相反：先还原业务表，再删快照表（保留快照直到验证通过）。
-- ⚠️ 还原前 MUST 确认无业务已在快照之后写入（否则会覆盖新数据）。
--    灰名单/菜单/密钥版本属低频写，风险可控；sys_job 由 Quartz 内存态驱动，
--    还原后 MUST 重启 web-admin 让内存 JobStore 重新加载。
-- ============================================================

-- ---------- 1. 还原菜单（先删后插，避免主键/唯一约束冲突） ----------
DELETE FROM SYS_MENU WHERE MENU_ID IN (SELECT MENU_ID FROM BAK_SYS_MENU_20261106);
INSERT INTO SYS_MENU SELECT * FROM BAK_SYS_MENU_20261106;
COMMIT;

-- ---------- 2. 还原定时任务（IT-056） ----------
DELETE FROM SYS_JOB WHERE JOB_ID = 405;
INSERT INTO SYS_JOB SELECT * FROM BAK_SYS_JOB_20261106;
COMMIT;

-- ---------- 3. 还原部门/岗位（B19） ----------
DELETE FROM SYS_DEPT WHERE DEPT_ID IN (SELECT DEPT_ID FROM BAK_SYS_DEPT_20261106);
INSERT INTO SYS_DEPT SELECT * FROM BAK_SYS_DEPT_20261106;
DELETE FROM SYS_POST WHERE POST_ID IN (SELECT POST_ID FROM BAK_SYS_POST_20261106);
INSERT INTO SYS_POST SELECT * FROM BAK_SYS_POST_20261106;
COMMIT;

-- ---------- 4. 还原密钥版本状态（若该表存在） ----------
BEGIN
  DELETE FROM PUBLIC_KEY_VERSION_STATUS
   WHERE (PROVIDER_ID, KEY_DOMAIN, KEY_VERSION) IN
         (SELECT PROVIDER_ID, KEY_DOMAIN, KEY_VERSION FROM BAK_KEY_VERSION_20261106);
  INSERT INTO PUBLIC_KEY_VERSION_STATUS SELECT * FROM BAK_KEY_VERSION_20261106;
  COMMIT;
EXCEPTION WHEN OTHERS THEN
  DBMS_OUTPUT.PUT_LINE('PUBLIC_KEY_VERSION_STATUS 还原跳过：' || SQLERRM);
END;
/

-- ---------- 5. 还原灰名单（表由 DDL 新建，还原＝清空后灌回快照；快照为空则只清空） ----------
BEGIN
  EXECUTE IMMEDIATE 'DELETE FROM GRAYLIST_OPERATE_LOG';
  FOR r IN (SELECT * FROM BAK_GRAYLIST_OPERATE_LOG_20261106) LOOP
    INSERT INTO GRAYLIST_OPERATE_LOG VALUES r;
  END LOOP;
  EXECUTE IMMEDIATE 'DELETE FROM GRAYLIST';
  FOR r IN (SELECT * FROM BAK_GRAYLIST_20261106) LOOP
    INSERT INTO GRAYLIST VALUES r;
  END LOOP;
  COMMIT;
EXCEPTION WHEN OTHERS THEN
  DBMS_OUTPUT.PUT_LINE('灰名单还原跳过（表可能不存在）：' || SQLERRM);
END;
/

-- ---------- 6. 验证还原结果 ----------
SELECT 'SYS_MENU' AS TBL, COUNT(*) AS ROWS FROM SYS_MENU
UNION ALL SELECT 'SYS_JOB(405)', COUNT(*) FROM SYS_JOB WHERE JOB_ID = 405
UNION ALL SELECT 'SYS_DEPT', COUNT(*) FROM SYS_DEPT
UNION ALL SELECT 'SYS_POST', COUNT(*) FROM SYS_POST
UNION ALL SELECT 'GRAYLIST', COUNT(*) FROM GRAYLIST
UNION ALL SELECT 'GRAYLIST_OPERATE_LOG', COUNT(*) FROM GRAYLIST_OPERATE_LOG;

